using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using Microsoft.Extensions.Options;
using SonAero.Platform.Integrations;

namespace Portal.Api.Services;

public sealed class IntegrationCredentialTestOptions
{
    public const string SectionName = "IntegrationCredentials";

    public string FulcrumBaseUrl { get; set; } = FulcrumApiEndpoint.ItarBaseUrl;
}

public sealed record IntegrationCredentialTestResult(
    bool Succeeded,
    string Message,
    int? HttpStatusCode);

public sealed class FulcrumCredentialTester(
    HttpClient httpClient,
    IOptions<IntegrationCredentialTestOptions> options)
{
    private static readonly (string Name, string Path, object Body)[] ReadChecks =
    [
        ("quotes", "api/reporting/quote/list?Skip=0&Take=1", new { }),
        ("inventory items", "api/items/list/v2?Skip=0&Take=1", new { latestRevision = true, isArchived = false }),
        ("jobs", "api/jobs/list?Skip=0&Take=1", new { }),
        ("sales orders", "api/sales-orders/list?Skip=0&Take=1", new { }),
        ("shipments", "api/shipments/list?Skip=0&Take=1", new { })
    ];

    public async Task<IntegrationCredentialTestResult> TestAsync(
        string configuredToken,
        CancellationToken cancellationToken)
    {
        var settings = options.Value;
        Uri baseUri;
        try
        {
            baseUri = FulcrumApiEndpoint.ResolveItarBaseUri(
                settings.FulcrumBaseUrl,
                "IntegrationCredentials:FulcrumBaseUrl");
        }
        catch (InvalidOperationException)
        {
            return new(false, "The Fulcrum API address is not configured as a secure HTTPS URL.", null);
        }

        var token = configuredToken.Trim();
        if (token.StartsWith("Bearer ", StringComparison.OrdinalIgnoreCase))
            token = token["Bearer ".Length..].Trim();

        httpClient.BaseAddress = baseUri;
        try
        {
            foreach (var check in ReadChecks)
            {
                using var request = new HttpRequestMessage(HttpMethod.Post, check.Path)
                {
                    Content = JsonContent.Create(check.Body)
                };
                request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", token);
                request.Headers.UserAgent.ParseAdd("SonAero-AdminCredentialTest/1.0");

                using var response = await httpClient.SendAsync(
                    request,
                    HttpCompletionOption.ResponseHeadersRead,
                    cancellationToken);
                if (response.IsSuccessStatusCode) continue;

                var statusCode = (int)response.StatusCode;
                var message = response.StatusCode switch
                {
                    HttpStatusCode.Unauthorized =>
                        "Fulcrum's ITAR API rejected the token. Confirm it was generated by this ITAR site and is current.",
                    HttpStatusCode.Forbidden =>
                        $"Fulcrum accepted the identity but the token does not have permission to view {check.Name}.",
                    _ => $"Fulcrum returned HTTP {statusCode} while checking {check.Name}. The token could not be verified for every connected module."
                };
                return new(false, message, statusCode);
            }

            return new(
                true,
                "Fulcrum accepted the token for quotes, inventory items, jobs, sales orders, and shipments.",
                StatusCodes.Status200OK);
        }
        catch (OperationCanceledException) when (!cancellationToken.IsCancellationRequested)
        {
            return new(false, "The Fulcrum connection test timed out.", null);
        }
        catch (HttpRequestException)
        {
            return new(false, "The application server could not reach the Fulcrum API.", null);
        }
    }
}
